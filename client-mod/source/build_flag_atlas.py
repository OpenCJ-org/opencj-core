"""Build the lossless 128px country atlas and its matching GSC lookup.
Sources are pinned SVGs under assets/flags. Requires Pillow and CairoSVG.
"""
from pathlib import Path
import argparse,hashlib,io,json,math,struct
from PIL import Image
import cairosvg

CLIENT=Path(__file__).resolve().parents[1]
CELL=160
FLAG=128
PAD=16
SIDE=1024
COLS=6
CAPACITY=36
SCRATCH_LIMIT=6*1024*1024
SHADER='opencj_flag_atlas'

def material(template,name):
    old=b'opencj_rank_1';delta=len(name)-len(old)
    data=bytearray(template)
    for offset,expected in [(0,old),(4,old),(64,b'colorMap'),(72,old)]:
        ptr=struct.unpack_from('<I',data,offset)[0]
        assert data[ptr:].split(b'\0',1)[0]==expected
    assert data[76:79]==b'2d\0'
    for offset in (4,72):struct.pack_into('<I',data,offset,struct.unpack_from('<I',data,offset)[0]+delta)
    struct.pack_into('<I',data,64,struct.unpack_from('<I',data,64)[0]+2*delta)
    struct.pack_into('<HH',data,24,SIDE,SIDE)
    data=bytearray(bytes(data).replace(old,name.encode()))
    for offset in (0,4,64,72):struct.pack_into('<I',data,offset,struct.unpack_from('<I',data,offset)[0]+len(SHADER)-2)
    return bytes(data[:76])+SHADER.encode()+b'\0'+bytes(data[79:])

def build(output,gsc_output):
    provenance=json.loads((CLIENT/'assets/flags/provenance.json').read_text())
    codes=provenance['codes']
    assert len(codes)==len(set(codes))==256 and codes==sorted(codes) and 'xx' not in codes
    pages=math.ceil(len(codes)/CAPACITY)
    for folder in ['images','materials','material_properties','techniques','techsets/sm2']:
        (output/folder).mkdir(parents=True,exist_ok=True)
    template=(CLIENT/'cod4/materials/opencj_rank_1').read_bytes()
    props=(CLIENT/'cod4/material_properties/opencj_rank_1').read_bytes()
    entries=[]
    payload_bytes=0
    for page in range(pages):
        atlas=Image.new('RGBA',(SIDE,SIDE))
        for slot,code in enumerate(codes[page*CAPACITY:(page+1)*CAPACITY]):
            svg=CLIENT/'assets/flags'/f'flag-icons-v7.5.0/{code}.svg'
            raw=svg.read_bytes()
            flag=Image.open(io.BytesIO(cairosvg.svg2png(bytestring=raw,output_width=FLAG,output_height=96))).convert('RGBA')
            square=Image.new('RGBA',(FLAG,FLAG));square.paste(flag,(0,16))
            tile=Image.new('RGBA',(CELL,CELL));tile.paste(square,(PAD,PAD))
            tile.paste(square.crop((0,0,1,FLAG)).resize((PAD,FLAG)),(0,PAD))
            tile.paste(square.crop((FLAG-1,0,FLAG,FLAG)).resize((PAD,FLAG)),(PAD+FLAG,PAD))
            tile.paste(tile.crop((0,PAD,CELL,PAD+1)).resize((CELL,PAD)),(0,0))
            tile.paste(tile.crop((0,PAD+FLAG-1,CELL,PAD+FLAG)).resize((CELL,PAD)),(0,PAD+FLAG))
            atlas.paste(tile,(slot%COLS*CELL,slot//COLS*CELL))
            entries.append({'code':code,'page':page,'selector':slot+1,'sha256':hashlib.sha256(raw).hexdigest()})
        levels=[atlas.resize((max(1,SIDE>>n),max(1,SIDE>>n)),Image.Resampling.LANCZOS).tobytes('raw','BGRA') for n in range(11)]
        sizes=[len(level) for level in levels]
        assert sum(sizes)<=SCRATCH_LIMIT
        header=b'IWi'+bytes([6,1,0])+struct.pack('<HHH',SIDE,SIDE,1)+struct.pack('<4I',*[28+sum(sizes[i:]) for i in range(4)])
        name=f'{SHADER}_{page}'
        (output/'images'/(name+'.iwi')).write_bytes(header+b''.join(reversed(levels)))
        (output/'materials'/name).write_bytes(material(template,name))
        (output/'material_properties'/name).write_bytes(props)
        payload_bytes+=sum(sizes)
    tech='{\n stateMap "default2d";\n vertexShader 1.1 "vertcol_simple.hlsl" { }\n pixelShader 2.0 "'+SHADER+'" { colorMapSampler = material.colorMap; }\n vertex.position = code.position;\n vertex.color[0] = code.color;\n vertex.texcoord[0] = code.texcoord[0];\n}\n'
    (output/'techniques'/(SHADER+'.tech')).write_text(tech)
    for folder in ['techsets','techsets/sm2']:(output/folder/(SHADER+'.techset')).write_text('"unlit":\n '+SHADER+';\n')
    text='''// Generated by client-mod/source/build_flag_atlas.py. Keep in sync with atlas assets.
resolve(country)
{
    if(!isDefined(level.countryAtlasSlots))
    {
        level.countryAtlasSlots=[];
        codes=strTok("CODES"," ");
        for(i=0;i<codes.size;i++)level.countryAtlasSlots[codes[i]]=i;
    }
    code="";
    if(isDefined(country))code=toLower(country);
    if(code=="uk")code="gb";
    result=spawnStruct();
    result.known=isDefined(level.countryAtlasSlots[code]);
    if(!result.known)
    {
        result.material="default";
        result.selector=0;
        return result;
    }
    index=level.countryAtlasSlots[code];
    page=int(index/36);
    result.material="opencj_flag_atlas_"+page;
    result.selector=index-page*36+1;
    return result;
}
'''.replace('CODES',' '.join(codes))
    gsc_output.parent.mkdir(parents=True,exist_ok=True);gsc_output.write_text(text)
    report={'source':provenance['source'],'format':'BGRA8, full mip chain','flag_content':[128,96],'cell':CELL,'padding':PAD,'dimensions':[SIDE,SIDE],'columns':COLS,'capacity':CAPACITY,'image_count':pages,'material_count':pages,'texture_payload_bytes':payload_bytes,'entries':entries}
    (CLIENT/'source/flag_atlas_manifest.json').write_text(json.dumps(report,indent=2)+'\n')
    print(f'{len(codes)} flags: {pages} materials, {pages} images; {payload_bytes} texture bytes')

if __name__=='__main__':
    p=argparse.ArgumentParser(description=__doc__)
    p.add_argument('--output',type=Path,default=CLIENT/'cod4')
    p.add_argument('--gsc-output',type=Path,default=CLIENT.parent/'server-gsc/opencj/flagatlas.gsc')
    args=p.parse_args();build(args.output,args.gsc_output)
